//! `CONTROL/control` and maintainer script generation (spec §8, §9, §18).
//!
//! The generated maintainer scripts are upgrade-aware (§18.1: idempotent,
//! tolerate re-running on upgrade) and service-aware (§11.2: packaged
//! service activation happens only when platform policy permits — gated on
//! the `/etc/pyxis/allow-packaged-services` flag file, never by default).
//! Developer-provided scripts in `<project>/packaging/` override the
//! generated ones verbatim.

use crate::config::Project;

/// Policy flag file: packaged service activation is opt-in per image.
pub const SERVICE_POLICY_FLAG: &str = "/etc/pyxis/allow-packaged-services";

/// Render `CONTROL/control`. `Package`/`Version` mirror the app identity
/// (spec §8.2: Package == appinfo.id, Version == appinfo.version).
pub fn render_control(project: &Project) -> String {
    let c = &project.config;
    let mut out = String::new();
    out.push_str(&format!("Package: {}\n", c.id));
    out.push_str(&format!("Version: {}\n", c.version));
    out.push_str(&format!("Architecture: {}\n", c.package.architecture));
    out.push_str(&format!("Section: {}\n", c.package.section));
    out.push_str(&format!("Priority: {}\n", c.package.priority));
    out.push_str(&format!("Maintainer: {}\n", project.maintainer()));
    if let Some(depends) = &c.package.depends {
        if !depends.is_empty() {
            out.push_str(&format!("Depends: {}\n", depends.join(", ")));
        }
    }
    out.push_str(&format!("Description: {}\n", project.description()));
    out
}

/// Installed unit paths for every shipped service.
fn service_unit_paths(project: &Project) -> Vec<String> {
    project
        .services()
        .iter()
        .map(|svc| project.service_unit_install_path(&svc.unit))
        .collect()
}

/// `postinst`: refresh the launcher registry, then (policy permitting)
/// enable+start shipped services. Idempotent — `systemctl enable` and
/// `pyxis-appctl rescan` are safe to re-run, so fresh installs and upgrades
/// (§18.1) take the same path.
pub fn render_postinst(project: &Project) -> String {
    let mut out = String::from(
        "#!/bin/sh\n\
         # Generated by Vroom (pyxis package). Runs on install AND upgrade.\n\
         set -e\n\
         if command -v pyxis-appctl >/dev/null 2>&1; then\n\
         \x20 pyxis-appctl rescan || true\n\
         fi\n\
         if command -v pyxis-cachectl >/dev/null 2>&1; then\n\
         \x20 pyxis-cachectl refresh-icons || true\n\
         fi\n",
    );
    let units = service_unit_paths(project);
    if !units.is_empty() {
        out.push_str(&format!(
            "# Packaged service activation is platform policy, not package right\n\
             # (spec section 11.2): only act when the image opts in.\n\
             if [ -f {SERVICE_POLICY_FLAG} ] && command -v systemctl >/dev/null 2>&1; then\n"
        ));
        for unit in &units {
            out.push_str(&format!("  systemctl enable --now {unit} || true\n"));
        }
        out.push_str("  systemctl daemon-reload || true\nfi\n");
    }
    out.push_str("exit 0\n");
    out
}

/// `prerm`: stop the app if it is running, then stop/disable shipped
/// services before their files disappear (§18.2). Also runs before an
/// upgrade's unpack, which is exactly when a running old version should be
/// stopped.
pub fn render_prerm(project: &Project) -> String {
    let mut out = format!(
        "#!/bin/sh\n\
         # Generated by Vroom (pyxis package). Runs before removal AND upgrade.\n\
         set -e\n\
         if command -v pyxis-appctl >/dev/null 2>&1; then\n\
         \x20 pyxis-appctl close {} 2>/dev/null || true\n\
         fi\n",
        project.config.id
    );
    let units = service_unit_paths(project);
    if !units.is_empty() {
        out.push_str("if command -v systemctl >/dev/null 2>&1; then\n");
        for unit in &units {
            let name = unit.rsplit('/').next().unwrap_or(unit);
            out.push_str(&format!(
                "  systemctl disable --now {name} 2>/dev/null || true\n"
            ));
        }
        out.push_str("fi\n");
    }
    out.push_str("exit 0\n");
    out
}

/// `postrm`: drop package-owned caches only (§18.2 — never user data), and
/// refresh the registry so the launcher entry disappears.
pub fn render_postrm(project: &Project) -> String {
    format!(
        "#!/bin/sh\n\
         # Generated by Vroom (pyxis package). Removes package-owned caches only;\n\
         # user data/profiles are never touched here (spec section 18.2).\n\
         set -e\n\
         rm -rf /var/cache/pyxis/{id} 2>/dev/null || true\n\
         if command -v systemctl >/dev/null 2>&1; then\n\
         \x20 systemctl daemon-reload || true\n\
         fi\n\
         if command -v pyxis-appctl >/dev/null 2>&1; then\n\
         \x20 pyxis-appctl rescan || true\n\
         fi\n\
         exit 0\n",
        id = project.config.id
    )
}
